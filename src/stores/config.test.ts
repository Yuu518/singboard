import { expect, it, vi } from 'vitest'
vi.mock('@tauri-apps/api/core', () => ({ invoke: vi.fn().mockResolvedValue(undefined) }))

it('drops the legacy custom service name when loading and saving settings', async () => {
  localStorage.setItem('singboard-config', JSON.stringify({ serviceName: 'custom-legacy-service', startupDelaySeconds: 45 }))
  const { useConfigStore } = await import('./config')
  const { config, updateConfig } = useConfigStore()
  expect(config.value).not.toHaveProperty('serviceName')
  expect(config.value.startupDelaySeconds).toBe(45)
  updateConfig({ startupDelaySeconds: 60 })
  await import('vue').then(({ nextTick }) => nextTick())
  expect(JSON.parse(localStorage.getItem('singboard-config')!)).not.toHaveProperty('serviceName')
  localStorage.clear()
})

it('defaults to tinted glass and mirrors the glass tint onto the root element', async () => {
  const { nextTick } = await import('vue')
  const { useConfigStore } = await import('./config')
  const { config, updateConfig } = useConfigStore()
  const root = document.documentElement
  expect(config.value.glassTint).toBe(1)
  expect(root.getAttribute('data-glass')).toBe('blur')
  expect(root.style.getPropertyValue('--glass-t')).toBe('1')
  updateConfig({ glassTint: 0.3 })
  await nextTick()
  expect(root.getAttribute('data-glass')).toBe('clear')
  expect(root.style.getPropertyValue('--glass-t')).toBe('0.3')
  updateConfig({ glassTint: 7 })
  await nextTick()
  expect(config.value.glassTint).toBe(1)
  updateConfig({ glassTint: 'frosted' as never })
  await nextTick()
  expect(config.value.glassTint).toBe(1)
  localStorage.clear()
})

it('carries the old clear glass mode over to the clear end of the slider', async () => {
  vi.resetModules()
  localStorage.setItem('singboard-config', JSON.stringify({ glassMode: 'clear' }))
  const { useConfigStore } = await import('./config')
  const { config } = useConfigStore()
  expect(config.value.glassTint).toBe(0)
  expect(config.value).not.toHaveProperty('glassMode')
  expect(document.documentElement.getAttribute('data-glass')).toBe('clear')
  localStorage.clear()
})

it('leaves no profile selected after deleting the active one, and keeps it that way after reload', async () => {
  const { nextTick } = await import('vue')
  vi.resetModules()
  localStorage.clear()
  const { useConfigStore } = await import('./config')
  const store = useConfigStore()
  const first = store.addConfigProfile('A', 'local', 'C:/a.json')
  const second = store.addConfigProfile('B', 'local', 'C:/b.json')
  store.setActiveConfigProfile(second)
  await nextTick()

  store.removeConfigProfile(second)
  await nextTick()
  expect(store.activeConfigProfileId.value).toBe('')
  expect(store.configProfiles.value.map((p) => p.id)).toEqual([first])

  vi.resetModules()
  const reloaded = (await import('./config')).useConfigStore()
  expect(reloaded.activeConfigProfileId.value).toBe('')
  localStorage.clear()
})

it('ignores Android-only root settings and keeps page swiping off on the desktop', async () => {
  vi.resetModules()
  localStorage.setItem('singboard-config', JSON.stringify({ rootMode: true, rulesDir: '/data/adb/box/rules' }))
  const { useConfigStore } = await import('./config')
  const { config } = useConfigStore()
  expect(config.value.rootMode).toBe(false)
  expect(config.value.rulesDir).toBe('')
  expect(config.value.pageSwipe).toBe(false)
  localStorage.clear()
})
